export const SUPPORTED_LANGUAGES = ['en', 'hi', 'kn'];

export const LANGUAGE_NAMES = { en: 'English', hi: 'Hindi', kn: 'Kannada' };

export function normalizeLanguage(value) {
  return SUPPORTED_LANGUAGES.includes(value) ? value : 'en';
}

/** Script-based detection so a Hindi/Kannada message gets a reply in that language. */
export function detectScriptLanguage(text) {
  if (typeof text !== 'string') return null;
  if (/[\u0900-\u097F]/.test(text)) return 'hi';
  if (/[\u0C80-\u0CFF]/.test(text)) return 'kn';
  return null;
}

